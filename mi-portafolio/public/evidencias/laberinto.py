def play_sound(sound_type):
    try:
        sample_rate = 44100
        duration = 0.15
        buf = bytearray()

        if sound_type == "error":
            # Sonido grave de choque/retroceso
            n_samples = int(sample_rate * duration)
            for i in range(n_samples):
                freq = 140 - (i / n_samples) * 90
                val = int(127 * (1 if (i * freq / sample_rate) % 1 > 0.5 else -1))
                buf.extend([val & 0xFF, val & 0xFF])
        elif sound_type == "move":
            # Paso normal
            duration = 0.05
            n_samples = int(sample_rate * duration)
            for i in range(n_samples):
                freq = 320 - (i / n_samples) * 120
                val = int(127 * math.sin(2 * math.pi * freq * i / sample_rate))
                buf.extend([val & 0xFF, val & 0xFF])
        elif sound_type == "cookie":
            # Sonido de recompensa
            duration = 0.18
            n_samples = int(sample_rate * duration)
            for i in range(n_samples):
                freq = 587 if i < n_samples / 2 else 880
                val = int(127 * math.sin(2 * math.pi * freq * i / sample_rate))
                buf.extend([val & 0xFF, val & 0xFF])
        elif sound_type == "win":
            # Arpegio de victoria
            duration = 0.4
            n_samples = int(sample_rate * duration)
            for i in range(n_samples):
                freq = [523, 659, 783, 1046][int(i / (n_samples / 4))]
                val = int(127 * math.sin(2 * math.pi * freq * i / sample_rate))
                buf.extend([val & 0xFF, val & 0xFF])
        else:
            return

        sound = pygame.mixer.Sound(buffer=bytes(buf))
        sound.set_volume(0.3)
        sound.play()
    except Exception:
        pass


# --- ESTRUCTURA DEL LABERINTO ---
class Cell:
    def __init__(self, r, c):
        self.r = r
        self.c = c
        # Paredes: [Arriba, Derecha, Abajo, Izquierda]
        self.walls = [True, True, True, True]
        self.visited = False


def generate_maze(rows, cols):
    grid = [[Cell(r, c) for c in range(cols)] for r in range(rows)]
    stack = []
    current = grid[0][0]
    current.visited = True

    while True:
        unvisited = []
        r, c = current.r, current.c
        if r > 0 and not grid[r - 1][c].visited:
            unvisited.append((grid[r - 1][c], 0))
        if c < cols - 1 and not grid[r][c + 1].visited:
            unvisited.append((grid[r][c + 1], 1))
        if r < rows - 1 and not grid[r + 1][c].visited:
            unvisited.append((grid[r + 1][c], 2))
        if c > 0 and not grid[r][c - 1].visited:
            unvisited.append((grid[r][c - 1], 3))

        if unvisited:
            chosen_cell, dir_idx = random.choice(unvisited)
            current.walls[dir_idx] = False
            chosen_cell.walls[(dir_idx + 2) % 4] = False
            stack.append(current)
            current = chosen_cell
            current.visited = True
        elif stack:
            current = stack.pop()
        else:
            break

    return grid


def solve_bfs(grid, start, end, rows, cols):
    queue = deque([[start]])
    visited = {start}

    while queue:
        path = queue.popleft()
        r, c = path[-1]
        if (r, c) == end:
            return path

        moves = [(-1, 0, 0), (0, 1, 1), (1, 0, 2), (0, -1, 3)]
        for dr, dc, wall in moves:
            if not grid[r][c].walls[wall]:
                nr, nc = r + dr, c + dc
                if 0 <= nr < rows and 0 <= nc < cols and (nr, nc) not in visited:
                    visited.add((nr, nc))
                    queue.append(path + [(nr, nc)])

    return []


