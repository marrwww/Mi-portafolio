# Importar librerías necesarias
import osmnx as ox
import pandas as pd
import numpy as np
from sklearn.cluster import KMeans
from sklearn.neighbors import KNeighborsClassifier
import matplotlib.pyplot as plt
import folium

# --- FASE A: EXTRACCIÓN Y LIMPIEZA ---
place_name = "Chalatenango, El Salvador"
print(f"Descargando datos para: {place_name}...")

# Descargar puntos de supermercados y tiendas de conveniencia de OSM usando la API actualizada
tags = {'shop': ['supermarket', 'convenience', 'grocery']}
gdf = ox.features_from_place(place_name, tags=tags)

print(f"Total de registros brutos extraídos: {len(gdf)}")

if not gdf.empty:
    # Obtener el centroide si la geometría es un polígono
    gdf['centroid'] = gdf.geometry.centroid
    gdf['latitude'] = gdf['centroid'].y
    gdf['longitude'] = gdf['centroid'].x

    # Seleccionar columnas disponibles
    cols_to_keep = ['name', 'shop', 'latitude', 'longitude']
    df = gdf[[c for c in cols_to_keep if c in gdf.columns]].copy()

    if 'name' not in df.columns:
        df['name'] = "Sin nombre"
    if 'shop' not in df.columns:
        df['shop'] = "supermarket"

    df.rename(columns={'shop': 'category'}, inplace=True)
    df['city'] = "Chalatenango"

    # Limpiar nulos y duplicados
    df = df.dropna(subset=['latitude', 'longitude'])
    df = df.drop_duplicates(subset=['latitude', 'longitude'])
    df = df.reset_index(drop=True)

    print(f"Registros limpios finales: {len(df)}")
    display(df.head())
else:
    print("⚠️ No se encontraron elementos con los filtros actuales.")

# --- FASE B: K-MEANS ---
X = df[['latitude', 'longitude']].values

# Aplicar K-Means con K=3 (ajustable según sus puntos)
k_optimo = min(3, len(X)) if len(X) >= 3 else 1
kmeans = KMeans(n_clusters=k_optimo, random_state=42, n_init=10)
df['cluster'] = kmeans.fit_predict(X)
centroides = kmeans.cluster_centers_

print("\nCoordenadas de los Centroides (Lat, Lon):")
print(centroides)

# --- FASE C: KNN ---
# Crear etiquetas de ejemplo basadas en la latitud media
lat_media = df['latitude'].mean()
df['zona_etiqueta'] = np.where(df['latitude'] >= lat_media, 'Zona Urbana Central', 'Zona Periférica')

X_train = df[['latitude', 'longitude']].values
y_train = df['zona_etiqueta'].values

# Entrenar KNN (K=3 vecinos)
k_vecinos = min(3, len(df))
knn = KNeighborsClassifier(n_neighbors=k_vecinos, metric='euclidean')
knn.fit(X_train, y_train)

# Ubicación propuesta (Ej: Coordenada de prueba en Chalatenango)
ubicacion_propuesta = np.array([[14.143, -88.938]])
clase_predicha = knn.predict(ubicacion_propuesta)
distancias, indices = knn.kneighbors(ubicacion_propuesta)

print(f"\nUbicación propuesta clasificada como: {clase_predicha[0]}")

# --- FASE D: MAPA INTERACTIVO ---
lat_centro = df['latitude'].mean()
lon_centro = df['longitude'].mean()
mapa = folium.Map(location=[lat_centro, lon_centro], zoom_start=11)

colores = ['red', 'blue', 'green', 'purple', 'orange']

# Agregar negocios
for idx, row in df.iterrows():
    color_c = colores[row['cluster'] % len(colores)]
    folium.CircleMarker(
        location=[row['latitude'], row['longitude']],
        radius=6,
        popup=f"<b>{row['name']}</b><br>Cat: {row['category']}<br>Cluster: {row['cluster']}",
        color=color_c,
        fill=True,
        fill_color=color_c
    ).add_to(mapa)

# Agregar centroides
for i, centroid in enumerate(centroides):
    folium.Marker(
        location=[centroid[0], centroid[1]],
        popup=f"<b>Centroide K-Means {i}</b>",
        icon=folium.Icon(color='black', icon='star', prefix='fa')
    ).add_to(mapa)

# Agregar ubicación propuesta
folium.Marker(
    location=ubicacion_propuesta[0],
    popup=f"<b>Ubicación Propuesta</b><br>KNN: {clase_predicha[0]}",
    icon=folium.Icon(color='green', icon='plus-circle', prefix='fa')
).add_to(mapa)

# Guardar y mostrar mapa
mapa.save("mapa_hotspots_chalatenango.html")
print("\n✨ ¡Mapa generado con éxito como 'mapa_hotspots_chalatenango.html' en los archivos de Colab!")
