import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns
from sklearn.cluster import KMeans
from sklearn.metrics import accuracy_score, classification_report
from sklearn.model_selection import train_test_split
from sklearn.neighbors import KNeighborsClassifier
from sklearn.preprocessing import StandardScaler

# --- 1. PREPARACIÓN DE DATOS (500 estudiantes) ---
np.random.seed(
    42
)  # Parámetro 'seed': Fija la semilla aleatoria para garantizar reproducibilidad (mismos resultados al volver a ejecutar).
n_estudiantes = 500  # Número total de registros (filas) que tendrá nuestro dataset sintético.

# Generar variables sintéticas realistas
horas_estudio = np.random.gamma(
    shape=3, scale=2, size=n_estudiantes
).clip(
    1, 25
)  # shape: Forma de la distribución Gamma (asimetría). scale: Escala (dispersión). size: Cantidad de valores a generar. .clip(): Limita los valores mínimos a 1 y máximos a 25.
asistencia = (
    np.random.beta(a=5, b=2, size=n_estudiantes) * 100
)  # a y b: Parámetros de la distribución Beta que determinan la forma en que se concentran los porcentajes de asistencia.
tareas_entregadas = (
    np.random.beta(a=4, b=2, size=n_estudiantes) * 100
)  # a=4, b=2: Simulan una distribución donde la mayoría de los estudiantes entregan un porcentaje alto de tareas.

# Calcular nota basada en un modelo lineal con algo de ruido aleatorio
ruido = np.random.normal(
    0, 5, n_estudiantes
)  # 0: Media de la distribución normal (centrada en 0). 5: Desviación estándar (magnitud del ruido o error aleatorio).
nota_examen = (
    (horas_estudio * 1.5) + (asistencia * 0.4) + (tareas_entregadas * 0.3) + ruido
).clip(
    0, 100
)  # .clip(0, 100): Asegura que ninguna nota baje de 0 ni suba de 100.

# Variable objetivo: Aprobado (1) si nota >= 60, Reprobado (0) en caso contrario
aprobado = (nota_examen >= 60).astype(int)

# Crear DataFrame
df = pd.DataFrame(
    {
        "Horas_Estudio": horas_estudio,
        "Asistencia": asistencia,
        "Tareas_Entregadas": tareas_entregadas,
        "Nota_Examen": nota_examen,
        "Aprobado": aprobado,
    }
)

print("--- Primeras filas del Dataset ---")
print(df.head())
print(f"\nDistribución de aprobados:\n{df['Aprobado'].value_counts()}")

# --- 2. K-MEANS: AGRUPAMIENTO ---
# Features para K-Means (excluimos la nota final y la etiqueta para evitar sesgo directo)
X_cluster = df[["Horas_Estudio", "Asistencia", "Tareas_Entregadas"]]

# Normalización indispensable para K-Means
scaler_kmeans = StandardScaler()
X_cluster_scaled = scaler_kmeans.fit_transform(
    X_cluster
)  # Estandariza los datos restando la media y dividiendo por la desviación estándar (media=0, varianza=1).

# K-Means con k = 3
kmeans_3 = KMeans(
    n_clusters=3, random_state=42, n_init=10
)  # n_clusters: Cantidad de grupos (clusters) a formar. random_state: Semilla para inicializar los centroides de forma reproducible. n_init: Número de veces que el algoritmo se ejecutará con diferentes centroides iniciales para elegir el mejor resultado.
df["Cluster_3"] = kmeans_3.fit_predict(X_cluster_scaled)

# K-Means con k = 4
kmeans_4 = KMeans(n_clusters=4, random_state=42, n_init=10)  # n_clusters=4: Ahora busca 4 grupos distintos de rendimiento.
df["Cluster_4"] = kmeans_4.fit_predict(X_cluster_scaled)

# Visualización rápida de k=3
plt.figure(figsize=(10, 5))
sns.scatterplot(
    data=df,
    x="Horas_Estudio",
    y="Asistencia",
    hue="Cluster_3",  # hue: Asigna un color diferente a cada punto según el cluster al que pertenece.
    palette="viridis",  # palette: Mapa de colores utilizado para los grupos.
    style="Aprobado",  # style: Cambia la forma del marcador (cruz, círculo, etc.) según si el estudiante aprobó o no.
)
plt.title("K-Means Clustering (k=3)")
plt.show()

# --- 3. KNN: CLASIFICACIÓN (75% Train, 25% Test) ---
X_knn = df[["Horas_Estudio", "Asistencia", "Tareas_Entregadas", "Nota_Examen"]]
y_knn = df["Aprobado"]

X_train, X_test, y_train, y_test = train_test_split(
    X_knn,
    y_knn,
    test_size=0.25,  # test_size=0.25: Define que el 25% de los datos se usará para pruebas y el 75% restante para entrenamiento.
    random_state=42,  # random_state=42: Asegura que la partición aleatoria sea exactamente la misma en cada ejecución.
)

# --- 4. EXPERIMENTACIÓN CON KNN (Diferentes valores de k y normalización) ---
k_values = [1, 3, 5, 7, 11, 15, 21]
resultados_norm = []
resultados_sin_norm = []

# Con Normalización
scaler_knn = StandardScaler()
X_train_scaled = scaler_knn.fit_transform(X_train)
X_test_scaled = scaler_knn.transform(
    X_test
)  # .transform(): Aplica los parámetros calculados en el entrenamiento (media y desviación) al conjunto de prueba para evitar fuga de datos (data leakage).

for k in k_values:
    # Modelo normalizado
    knn_norm = KNeighborsClassifier(
        n_neighbors=k
    )  # n_neighbors=k: Número de vecinos cercanos que se consultarán para clasificar un nuevo punto de datos.
    knn_norm.fit(X_train_scaled, y_train)
    acc_norm = accuracy_score(y_test, knn_norm.predict(X_test_scaled))
    resultados_norm.append(acc_norm)

    # Modelo sin normalizar
    knn_sin = KNeighborsClassifier(n_neighbors=k)
    knn_sin.fit(X_train, y_train)
    acc_sin = accuracy_score(y_test, knn_sin.predict(X_test))
    resultados_sin_norm.append(acc_sin)

# Mostrar tabla comparativa de experimentación
df_experimento = pd.DataFrame(
    {
        "k": k_values,
        "Exactitud_Normalizado": resultados_norm,
        "Exactitud_Sin_Normalizar": resultados_sin_norm,
    }
)
print("\n--- Resultados de Experimentación KNN ---")
print(df_experimento)

# --- 5. DESAFÍO FINAL: PREDICCIÓN DE CASO ---
# Estudiante: 4 horas de estudio, 55% asistencia, 50% tareas entregadas, nota estimada aproximada (~45)
estudiante_nuevo = pd.DataFrame(
    [[4.0, 55.0, 50.0, 48.0]],
    columns=["Horas_Estudio", "Asistencia", "Tareas_Entregadas", "Nota_Examen"],
)

# Usamos el mejor k encontrado (ej: k=5 normalizado)
mejor_k = 5
knn_final = KNeighborsClassifier(
    n_neighbors=mejor_k
)  # n_neighbors=5: Utiliza los 5 vecinos más cercanos para tomar la decisión por votación mayoritaria.
knn_final.fit(X_train_scaled, y_train)

estudiante_scaled = scaler_knn.transform(estudiante_nuevo)
prediccion = knn_final.predict(estudiante_scaled)
probabilidad = knn_final.predict_proba(
    estudiante_scaled
)  # predict_proba(): Devuelve el porcentaje o probabilidad estimada de pertenecer a cada clase (0 o 1).

print("\n--- Desafío Final ---")
resultado_texto = "Aprobará" if prediccion[0] == 1 else "Reprobará"
print(f"Predicción para el estudiante: {resultado_texto}")
print(f"Probabilidades (Reprobar, Aprobar): {probabilidad[0]}")